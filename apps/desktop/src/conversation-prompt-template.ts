/** Editable starter for conversations without a saved template; saved clearing is respected. */
export const SCENE_PROMPT_CONSTRAINT_TEMPLATE = `# 本会话任务与输出约定
- 以下制作要求只适用于本次请求涉及的交付物；普通讨论和其他任务按我本次请求回答，不强制生成场次或分镜。
- 任务目标、改编范围、交付物、语言：以我本次请求为准；缺少关键前提时先说明需要确认的内容。
- 创作前按需检索并阅读本项目已保存的大纲、剧本、角色、场景和提示词；区分草稿与已发布资料，不把未读取的资料当作已知事实。
- 保留已有描述和确认设定。修改时只改变我要求的部分，并把相关细节完整带入最终交付；有冲突时指出冲突，不擅自删除或覆盖。

# 故事时间、地点与环境
- 故事年代／具体日期：[填写或沿用项目设定]
- 季节、一天中的时段、天气：[填写或沿用剧情；每场和每镜均须写明，不得遗漏]
- 地点、内外景、空间布局、地理与文化背景：[填写或按剧情确定]
- 明确故事时间与镜头播放时间的区别。跨时段、闪回、天气变化和转场要交代清楚；不要虚构无依据的精确日期。

# 统一视觉风格与连续性
- 视觉媒介／参考风格：[例如写实电影、二维动画、三维动画；不得混用]
- 色彩、对比度、材质、颗粒、镜头质感：[填写]
- 光源、光线方向、色温、阴影和氛围：[填写；随故事时间合理变化]
- 人物外观、发型、服装、配饰、道具、伤痕和角色关系：沿用已确认资料，保持跨镜头一致；需要变化时写清变化原因与发生位置。
- 场景布局、角色站位、视线、运动方向、轴线、道具状态：前后镜头连续，避免人物、物品和环境无故变化。
- 图片与视频使用已确认参考图／素材绑定；同一角色和场景复用相同来源。角色／场景图片提示词与场次／镜头视频提示词按各自用途编写。

# 角色设定板与视频参考图
- 角色图片默认交付供视频生成使用的完整角色设定板。至少包含同一人物的正面、侧面、背面全身三视图，清楚展示头顶至鞋底；三视图保持相同比例、年龄、面容、发型、服装、配饰和材质，不把不同姿态或表情图当成三视图。
- 同板补充正侧面头部特写、发型与发髻细节、服装结构与纹样、关键配饰、鞋履、标志道具及辨识特征的局部放大；可增加表情差分和材质色彩说明，分区清晰、细节可辨、不遮挡主体。
- 全部角色沿用同一项目美术标准，统一绘制方式、写实程度、人体比例、线条、上色、材质与光影；角色体型和年龄差异不能导致画风改变。相同版式不等于相同画风。
- 单幅剧情剧照、树下坐姿画面或只有一个角度的人物图，不满足完整角色设定板的交付要求。缺少三视图、局部细节或人物跨视图不一致时，应明确指出缺项并补齐，不能仅因图片返回成功就宣称验收合格。
- 生成视频时，将已确认的完整角色设定板作为对应角色的外观参考实际传入模型，并在提示词中说明各分区均为同一人物的不同视角与细节；文字、边框、色卡、面板和重复人物只用于参考，不要求出现在成片中。风格参考约束画法，角色身份分别绑定，避免不同角色共用同一张脸。
- 区分角色设定板参考与视频首帧用途。依据所选模型实际支持的参考图参数传入，保留用户选择的完整设定板；需要首帧时另行按分镜准备，不自动把整张设定板当作需要运动的首帧。模型能力不足时说明具体限制。

# 场次编排
- 根据地点、故事时间、人物目标、冲突和事件因果划分场次；不为了凑够 15 秒或某个模型时长改变剧情、增删事件或机械拼镜。
- 每场写明：场次编号与标题、故事时间、内外景与地点、天气、人物、剧情目标、冲突、情绪变化、事件顺序、起止状态和衔接方式。
- 根据动作、台词和叙事节奏估算自然时长。超过所选模型能力时保留完整场次，按自然镜头或动作节点分段，并说明各段的衔接。

# 每个分镜必须写清
- 镜头编号、所属场次、叙事目的、故事时间、镜头起止播放时间与预计时长。
- 地点／环境／天气，出镜人物和外观服装，站位、视线、道具及初始状态。
- 景别、机位角度、构图、焦段或透视、景深、焦点对象；运镜方向、速度与起止位置。
- 动作分解、节奏与情绪变化；多人动作写清先后、对象和互动，不能只写抽象形容词。
- 光线、色彩、材质与统一风格；对白写明说话者及原文，注明旁白、环境声、音效、音乐和无对白状态。
- 镜头结束状态、与前后镜头的连续性、转场；对应参考素材及必须保持和必须避免的内容。
- 输出每镜完整可用的提示词，不用“同上”“沿用前镜”代替关键信息；无内容的项写“不适用”或“无”，待确认的事实明确标记。

# 完整场次视频提示词与生成参数
- 场次视频提示词包含整体设定、连续性规则和该场所有镜头的完整提示词，按顺序排列，不遗漏或只提供摘要。
- 发起生成前，将完整场次提示词写入生产表单；根据剧情、参考素材和所选模型实际支持的参数填写生成方式、画幅、分辨率、时长及音频等字段。
- 叙事时长先按剧情推导；模型不支持的字段不得编造，限制或冲突应说明；实际提交前遵循软件的确认流程。
- 交付前逐场逐镜检查时间、地点、风格、人物、动作、对白、连续性、时长和素材引用是否齐全。`;

export function composeConversationPrompt(userPrompt: string, template?: string): string {
  const constraint = template?.trim();
  return constraint
    ? `【本会话要求约束】\n${constraint}\n\n【用户本次请求】\n${userPrompt}`
    : userPrompt;
}
